INSERT INTO appeals (
    title, description, category_id, status, priority,
    created_at, updated_at, resolved_at
)
SELECT
    s.title,
    s.description,
    c.id,
    s.status,
    s.priority,
    CURRENT_TIMESTAMP - s.days_ago * INTERVAL '1 day',
    CURRENT_TIMESTAMP - (s.days_ago - s.days_to_update) * INTERVAL '1 day',
    CASE
        WHEN s.status IN ('resolved', 'closed')
            THEN CURRENT_TIMESTAMP - (s.days_ago - s.days_to_update) * INTERVAL '1 day'
        ELSE NULL
    END
FROM sample_data AS s
JOIN categories AS c ON c.name = s.category_name
WHERE NOT EXISTS (
    SELECT 1 FROM appeals AS a WHERE a.title = s.title
);

